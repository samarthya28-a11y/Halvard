"""Run the Phase 1 acceptance scenarios and write docs/07-phase1-evidence.md from the real outputs."""
import hashlib, io, json, os, pathlib, subprocess, sys, tempfile, time, contextlib
ROOT = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "src")); sys.path.insert(0, str(ROOT / "tests"))
import warnings; warnings.simplefilter("ignore")
from helpers import make_agent, ManualClock
from halvard.ward import simulate as sim
from halvard.ward.incident import render
from halvard.ledger.audit import AuditLog, verify_export
from halvard.tenancy import TenantStore, TenantContext, TenantIsolationError
from halvard.coverage import CoverageMonitor
from halvard.relay.actions import Principal
from halvard.setup.guide import GuidedSetup
from halvard import perf

out = []
def H(t): out.append(f"\n## {t}\n")
def P(t=""): out.append(t)
def code(t): out.append("```\n" + t.rstrip() + "\n```")

P("# Phase 1 evidence\n")
P(f"Generated by `tools/run_acceptance.py` on {time.strftime('%Y-%m-%d %H:%M UTC', time.gmtime())}. Every number below is the output of that run; "
  "nothing is hand-written. Read the **Not demonstrated** section before relying on any of this.")

# ---- test suite + mutation
env = dict(os.environ, PYTHONWARNINGS="ignore")
t = subprocess.run([sys.executable, "-W", "ignore", "-m", "unittest", "discover", "-s", "tests"], cwd=ROOT, capture_output=True, text=True, env=env)
H("Test suite"); code("\n".join(t.stderr.strip().splitlines()[-4:]))
m = subprocess.run([sys.executable, "tools/mutation_check.py"], cwd=ROOT, capture_output=True, text=True, env=dict(env, HALVARD_SKIP_PERF="1"))
H("Do the tests bite? (remove a behavior, the suite must fail)"); code(m.stdout)
P("Caveat: a mutation is 'killed' when the suite goes red. A few mutations could go red by crashing rather than by an assertion; "
  "the named behavior tests in `tests/` are the specific guards.")

# ---- A1 offline ransomware
tmp = tempfile.mkdtemp(); a, host, clock, fs = make_agent(tmp); a.set_online(False)
root = os.path.join(tmp, "docs"); sim.authorize(root); paths = sim.seed_files(root, 60)
orig = {p: hashlib.sha256(pathlib.Path(p).read_bytes()).hexdigest() for p in paths}
host.spawn(4242, "halvard-safe-simulation"); touched = sim.run_simulation(fs, 4242, root)
back = sum(1 for p in paths if os.path.exists(p) and hashlib.sha256(pathlib.Path(p).read_bytes()).hexdigest() == orig[p])
left = list(pathlib.Path(root).rglob("*.locked"))
tenant = AuditLog(os.path.join(tmp, "tenant.log"), "acme", b"t" * 32, clock); a.set_online(True); rec = a.sync(tenant)
H("A1. Simulated ransomware burst on an OFFLINE laptop is stopped and the journal restores the files")
code(f"files in authorized test folder: {len(paths)}\nfiles touched before Ward froze the process: {touched}\nprocess state: {host.proc(4242)['state']}; file access blocked: {4242 in a.blocked}\n"
     f"files byte-identical to original after rollback: {back} of {len(paths)}\nleftover *.locked files: {len(left)}\n"
     f"device ledger verifies: {a.spool.verify()[0]}; spool ingested into tenant ledger after reconnect: {rec['kind']}; tenant ledger verifies: {tenant.verify()[0]}")
P("Plain-language incident page produced for the non-security reader:"); code(render(a.incidents[0], "LT-17"))
P("The simulation ran through `halvard.ward.simulate`, which refuses any directory without the customer's authorization marker. "
  "The OS file hook is simulated by `ProtectedFS` (see Not demonstrated).")

# ---- coverage
clock2 = ManualClock(); s = TenantStore(); s.create_tenant("acme", "Acme"); c = TenantContext("acme", "u", "it_admin")
s.put_entity(c, "srv-fin", "device", "Finance DB server", clock2.now(), criticality="crown_jewel")
s.put_entity(c, "lt-1", "device", "Laptop 1", clock2.now()); s.put_sensor(c, "s1", "lt-1", "ward", clock2.now())
mon = CoverageMonitor(s, c, clock2); g0 = mon.evaluate()
H("A4. A missing agent on a crown-jewel server raises a coverage incident")
code("Immediately: " + "; ".join(f"{g.name}: {g.severity.upper()} - {g.reason}" for g in g0) + "\nHealthy laptop (checked in): not listed.")
clock2.advance(800); s.heartbeat(c, "s1", clock2.now())
P("The promised check-in interval is a per-sensor field (default 900 s). A silent agent is flagged only after it passes. The monitor raises the gap on its next evaluation; the scheduler that calls it on a fixed cadence is not built, so the end-to-end 'within the promised interval' latency is not yet demonstrated.")
clock2.advance(1000); code("after 1000 s of silence: " + "; ".join(f"{g.name}: {g.severity}" for g in mon.evaluate()))

# ---- auditor export
log = AuditLog(os.path.join(tmp, "x.log"), "acme", b"k" * 32, ManualClock())
log.append("relay.action_executed", "u-7", "analyst", "LT-17", {"action": "isolate_host", "path": r"C:\Users\jsmith\Layoffs plan.docx", "user": "jsmith", "reason": "phishing click"}, controls=("RELAY.ISOLATE_HOST",))
log.append("ward.bulk_encryption_detected", "system", "system", "LT-17", {"confidence": 0.9}, controls=("WARD.BEHAVIORAL_STOP",))
exp = log.export_for_control("RELAY.ISOLATE_HOST"); blob = json.dumps(exp, indent=1)
H("A5. An auditor exports evidence for one control without receiving raw employee content")
code(f"employee identifiers planted in the source log: jsmith, 'Layoffs plan.docx', C:\\Users\\...\nappear in export: {[x for x in ('jsmith','Layoffs','C:') if x in blob]}\n"
     f"export verifies without any key: {verify_export(exp)[0]}\nentries visible: {sum(1 for e in exp['entries'] if not e.get('elided'))}; other-control entries elided with hashes kept: {sum(1 for e in exp['entries'] if e.get('elided'))}")
code(json.dumps(exp["entries"][0], indent=1))

# ---- tenancy
st = TenantStore(objects_root=os.path.join(tmp, "obj")); [st.create_tenant(t_, t_) for t_ in ("acme", "globex")]
ca, cg = TenantContext("acme", "u", "it_admin"), TenantContext("globex", "u", "it_admin"); st.put_entity(cg, "g-srv", "device", "G", 0); st.put_object(cg, "r/q3.txt", b"x")
res = []
for name, fn in (("read other tenant's entity", lambda: st.get_entity(ca, "g-srv")), ("list shows other tenant's entity", lambda: "g-srv" in st.list_entities(ca)),
                 ("read other tenant's object", lambda: st.get_object(ca, "r/q3.txt")), ("path traversal into other tenant", lambda: st.get_object(ca, "../globex/r/q3.txt")),
                 ("forged tenant id", lambda: st.get_entity(TenantContext("x' OR '1'='1", "u", "it_admin"), "g-srv"))):
    try: r = fn(); res.append(f"{name}: {'FAILED CLOSED (empty)' if r is False else 'ALLOWED!'}")
    except (KeyError, TenantIsolationError) as e: res.append(f"{name}: refused ({type(e).__name__})")
H("A6. A cross-tenant access test fails"); code("\n".join(res))

# ---- setup
tmp2 = tempfile.mkdtemp(); a2, h2, c2, fs2 = make_agent(tmp2, accepted=()); gs = GuidedSetup(a2, fs2, Principal("u-admin", "it_admin"), os.path.join(tmp2, "w")); lines = []
while gs.next_step():
    k, ti = gs.next_step(); r = gs.run_current(); lines.append(f"[{'ok' if r.ok else 'FAIL'}] {ti}: {r.happened}")
H("A7. A generalist completes day-one setup using only the in-product guide")
code("\n".join(lines) + "\n" + gs.progress())
P("The test drives the guide using only `next_step()` / `run_current()`; it contains no knowledge of the steps. "
  "A human usability trial with a real IT generalist has **not** been run.")

# ---- perf
r = perf.run_median(); H("A8. Agent performance budget on a normal-workday trace")
code(json.dumps(perf.BUDGET, indent=1)[:900] + "\n...\n\nMEASURED\n" + json.dumps(r, indent=1))
P("This measures the Python reference build on a cloud VM with a stated slow-machine multiplier. It shows the **method and the gate**. "
  "It is not a measurement of a native agent on a real five-year-old PC.")

H("Not demonstrated (so not claimed)")
for x in ("A2 stolen session cannot act after Signet revocation + Ward isolation: Signet is Phase 3.",
          "A3 malicious mailed attachment and the device that opened it as one case: Courier is Phase 4.",
          "Kernel-level interception: `ProtectedFS` is the contract for the native minifilter / Endpoint Security / fanotify component. That component, the Windows installer, and the Windows/macOS/Linux isolation adapters are not built or run here; isolation rules are only rendered as text and unit-tested.",
          "Machine-learning verdicts: `BaselineModel` is a hand-weighted static baseline and is labelled as such. No detection-rate claim is made. No public detection-test report exists yet (F129).",
          "Real asymmetric signing, customer-managed keys (HSM/KMS), SSO + phishing-resistant MFA, the cloud control plane, console UI, localization and accessibility: not in Phase 1 code.",
          "Real-hardware performance: no five-year-old PC lane exists yet.",
          "Ransomware that encrypts slowly (below 8 files / 30 s), or only files in journal-excluded paths, is not stopped by this detector alone. See the threat model.")  :
    P("- " + x)

(ROOT / "docs" / "07-phase1-evidence.md").write_text("\n".join(out) + "\n")
print("wrote docs/07-phase1-evidence.md; suite:", "OK" if t.returncode == 0 else "FAILED")
