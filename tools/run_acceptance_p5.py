"""Run the Phase 5 scenarios and write docs/16-phase5-evidence.md from real outputs. MUT_OUT=<file> embeds an existing mutation sweep."""
import io, json, os, pathlib, subprocess, sys, time, warnings, contextlib
ROOT = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "src")); sys.path.insert(0, str(ROOT / "tests")); warnings.simplefilter("ignore")
from rig5 import *
from halvard import cli
from halvard.atlas import posture as P
from halvard.atlas.saas import SaasCatalog
from halvard.coverage import CoverageMonitor
from halvard.vaultline.classifiers import Classifier, verhoeff_check_digit
from halvard.vaultline.inspection import InspectionPolicy

out = []
H = lambda t: out.append(f"\n## {t}\n"); P_ = lambda t="": out.append(t)
def code(t): out.append("```\n" + str(t).rstrip() + "\n```")
env = dict(os.environ, PYTHONWARNINGS="ignore")
P_("# Phase 5 evidence\n")
P_(f"Generated by `tools/run_acceptance_p5.py` on {time.strftime('%Y-%m-%d %H:%M UTC', time.gmtime())}. Every output is from that run. "
   "The cloud account is a **reference model written by the same author as the checks**; classifiers are validated pattern matchers, not a trained model. Read **Not demonstrated**.")
t = subprocess.run([sys.executable, "-W", "ignore", "-m", "unittest", "discover", "-s", "tests"], cwd=ROOT, capture_output=True, text=True, env=env)
H("Test suite"); code("\n".join(t.stderr.strip().splitlines()[-4:]))
mo = os.environ.get("MUT_OUT"); mtxt = pathlib.Path(mo).read_text() if mo and pathlib.Path(mo).exists() else subprocess.run([sys.executable, "tools/mutation_check.py"], cwd=ROOT, capture_output=True, text=True, env=env).stdout
H("Do the tests bite? (full sweep on throwaway copies)"); code(mtxt); P_(f"Killed: {mtxt.count('KILLED')}; survived or skipped: {mtxt.count('SURVIVED') + mtxt.count('SKIP')}.")

H("E1. A bucket holding customer card numbers is opened to the internet, and closed again (acceptance)")
buf = io.StringIO()
with contextlib.redirect_stdout(buf): cli.exposed_bucket()
code(buf.getvalue())

H("E2. Card data leaves a laptop with no network: USB, then email (acceptance)")
buf = io.StringIO()
with contextlib.redirect_stdout(buf): cli.data_leak()
code(buf.getvalue())
P_("Every decision above was made on the device from the signed policy bundle. The audit record kept labels and counts and no card numbers; that is asserted by a test, not only shown here.")

H("E3. Classification: what it recognises and what it refuses to call regulated")
C = Classifier(); rows = []
def show(label, name, data):
    c = C.classify(name, data); rows.append(f"{label:52} -> " + (", ".join(f"{k} x{v['count']} ({v['confidence']})" for k, v in c.labels.items()) or (f"unreadable: {c.unscannable}" if c.unscannable else "nothing")) + f"  [{c.sensitivity}]")
aad = "23456789012" + verhoeff_check_digit("23456789012")
show("CSV with 3 valid card numbers and card words", "a.csv", CARD_CSV)
show("same digits, but last digit changed (fails checksum)", "b.csv", CARD_CSV.replace(b"4111111111111111", b"4111111111111112").replace(b"5555555555554444", b"5555555555554445").replace(b"378282246310005", b"378282246310006"))
show("order numbers, phone, invoice id, part 000-00-0000", "c.txt", b"Order 4111111111111112 shipped. Tel 0044 20 7946 0958. Invoice 20260415. Part 000-00-0000.")
show("IBAN (valid) and Aadhaar (valid checksum)", "d.txt", f"Pay GB82WEST12345698765432. Aadhaar {aad[:4]} {aad[4:8]} {aad[8:]}".encode())
show("cloud key and a private key header", "e.env", SECRET_ENV)
show("PDF with a card number inside", "f.pdf", b"%PDF-1.4 " + b"4111111111111111")
show("ordinary meeting notes", "g.txt", PLAIN)
code("\n".join(rows)); P_("No matched value is returned or stored. Confidence is rule-assigned; the reason accompanies every label.")

H("E4. The consent gate")
now = 1_000_000.0; base = dict(enabled=True, purpose="prevent card data leaving the company", scope=["/data/*"], notice_id="N-1", notice_effective_at=now - 1)
L = []
for label, kw, path in (("everything in place", {}, "/data/o.csv"), ("inspection off", {"enabled": False}, "/data/o.csv"), ("no stated purpose", {"purpose": ""}, "/data/o.csv"), ("no staff notice", {"notice_id": None}, "/data/o.csv"),
                        ("notice not yet in effect", {"notice_effective_at": now + 99}, "/data/o.csv"), ("outside the scope", {}, "/elsewhere/o.csv"), ("personal folder", {}, "/data/personal/diary.txt")):
    ok, why = InspectionPolicy(**{**base, **kw}).check(path, now); L.append(f"{label:28} -> {'allowed' if ok else 'REFUSED: ' + why}")
code("\n".join(L))

H("E5. Cloud posture: findings, ordering, internet-to-data paths")
w = World5(); w.scan_all(); fs = w.cp.atlas.run_posture()
code("\n".join(f"[{f.severity:8}] {f.check_id:22} {f.resource:18} {f.exposure:8} {f.why[:80]}" for f in fs) + "\n\nInternet-to-data paths:\n" + "\n".join(("  CRITICAL " if p["critical"] else "           ") + p["path"] for p in w.cp.atlas.paths()))
P_("These are Halvard's own checks. No claim of conformance with CIS or any other benchmark is made.")

H("E6. Cloud workloads: coverage and policy consistency")
w = World5(); cp = w.cp; mon = CoverageMonitor(cp.store, cp.ctx, w.clock); L = ["before enrolment: " + "; ".join(f"{g.name}: {g.severity.upper()} - {g.reason}" for g in mon.evaluate())]
agent, host, _, fs_ = make_agent(os.path.join(w.tmp, "iweb"), prevention={"bulk_encryption": "audit_only", "known_bad": "enforce"}); agent.device_id = "i-web"; cp.fleet.register(agent); cp.atlas.enroll_workload("i-web", agent)
L.append("after enrolling i-web: " + "; ".join(f"{g.name}: {g.severity}" for g in mon.evaluate()))
L += ["policy drift: " + f["why"] for f in cp.atlas.workload_policy_findings(cp.fleet)]; L.append("policy pushed to the workload through the same signed-bundle path as a laptop: " + cp.push_dlp(w.dlp)["i-web"])
code("\n".join(L))

H("E7. SaaS discovery and risk rubric")
w = World5(); idp = w.cp.idp; idp.add_app("evil", "Shiny Mail Tool", publisher_verified=False, created_at=w.clock.now() - 2 * 86400); idp.grant_consent("alice@acme.com", "evil", ["Mail.Read", "Files.ReadWrite.All"])
cat = SaasCatalog(sanctioned=["files.acme-approved.example"], personal=["dropbox.com"])
apps = cat.discover(idp, [("alice", "dropbox.com", 80 << 20), ("alice", "files.acme-approved.example", 10), ("carol", "random-share.example", 5)])
code("\n".join(f"{a.name:26} {a.state:13} users={len(a.users)}  {cat.rate(a)['rating']:6} {'; '.join(cat.rate(a)['reasons'])[:90]}" for a in apps))

H("Not demonstrated (so not claimed)")
for x in ("A real AWS (or Azure, Google Cloud) account. The reference account models what decides exposure and enforces it, but real connectors, credentials, rate limits, regions and eventual consistency are unbuilt. Only AWS-shaped; Azure and Google Cloud do not exist here.",
          "Container and Kubernetes (F003, F089), infrastructure-as-code checks (F090), secrets in repositories (F088), backup immutability (F092), and API anomaly detection (F091).",
          "Reads made while a bucket was public: Halvard reverts the exposure and says the reads cannot be undone, but it does not read real access logs to say who accessed what.",
          "Classification quality on real documents: validated pattern matching with hand-set confidence; no trained model; PDFs, legacy Office files and images are reported unreadable. Deliberate test card numbers validate by design.",
          "Interception points: the device hook contract (`ProtectedFS.copy_out`/`send_out`) stands in for native USB, print and browser hooks that are not built; email is decided in the reference mail platform. A user who photographs a screen or uses a path with no hook is not detected.",
          "Encryption enforcement: status and device health only. F086 insider-risk scoring is not built.",
          "Performance cost of classification on the device is not in the published budget.",
          "Everything in the earlier phases' 'Not demonstrated' lists still applies.")  :
    P_("- " + x)
(ROOT / "docs" / "16-phase5-evidence.md").write_text("\n".join(out) + "\n"); print("wrote docs/16-phase5-evidence.md; suite:", "OK" if t.returncode == 0 else "FAILED")
